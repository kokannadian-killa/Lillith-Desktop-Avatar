#!/usr/bin/env bash
# One command, from the repo root (Linux / WSL):
#
#     windows/build.sh
#
# Cross-builds lillith.exe + lillith-settings.exe + lillith-admin.exe for
# x86_64-pc-windows-gnu,
# stages them with the atlas pages Lillith needs (no GGUF, no models), and
# writes to $DIST (default: <target dir>/dist/windows):
#   Lillith-<version>-setup.exe              NSIS installer (per-user)
#   Lillith-<version>-windows-x64.zip        portable folder
#   SHA256SUMS
#
# Needs: rustup target x86_64-pc-windows-gnu, mingw-w64 (x86_64-w64-mingw32-gcc),
# nsis (makensis), python3 + Pillow (icon only, if windows/lillith.ico is missing). Nothing is downloaded at
# install or run time; this script only fetches crates if Cargo has to.
#
# All-in-one: if bundle/llama/windows-x64/ holds the pinned llama-server
# (tools/bundle/make-bundle.sh --fetch-only, on this build machine), it is
# staged as bundle\llama\windows-x64\ and the installer pre-selects it.
#
# Env: CARGO (cargo binary, default `cargo`), CARGO_TARGET_DIR, DIST,
#      SKIP_BUILD=1 (reuse the last release build), NO_ZIP=1,
#      NO_LLAMA=1 (leave the bundled llama-server out),
#      LILLITH_MATTE_MODEL=<isnet-anime.onnx> (Pose Builder's AI cut-out model,
#        176 MB; default /workspace/lillith/matte-dl/isnet-anime.onnx). It is
#        sha256-checked and staged as models\rembg\isnet-anime.onnx (never in
#        git, never downloaded); a missing model fails the build unless
#        NO_MATTE_MODEL=1,
#      VOICE_PAYLOAD=<lillith-voice-win-<id>.zip> (from
#        tools/lillith-voice/windows/build-voice-win.sh): adds Lillith's voice
#        (cloned voice, p1 fallback, offline STT; ~1.3 GB) to the installer
#        (section "Lillith's voice" -> %LOCALAPPDATA%\Lillith\voice, HKCU Run
#        autostart) and to the portable zip (Lillith\voice\ + "Start Lillith
#        with voice.cmd"). Without it both are built without voice, as before.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
TARGET=x86_64-pc-windows-gnu
CARGO="${CARGO:-cargo}"
TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"
DIST="${DIST:-$TARGET_DIR/dist/windows}"
STAGE="$TARGET_DIR/windows-stage/Lillith"
export CARGO_TARGET_X86_64_PC_WINDOWS_GNU_LINKER="${CARGO_TARGET_X86_64_PC_WINDOWS_GNU_LINKER:-x86_64-w64-mingw32-gcc}"
export CC_x86_64_pc_windows_gnu="${CC_x86_64_pc_windows_gnu:-x86_64-w64-mingw32-gcc}"
export AR_x86_64_pc_windows_gnu="${AR_x86_64_pc_windows_gnu:-x86_64-w64-mingw32-ar}"

need() { command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' not found. $2" >&2; exit 1; }; }
need "$CARGO" "Install Rust (rustup) or set CARGO=/path/to/cargo."
need x86_64-w64-mingw32-gcc "Install mingw-w64 (Debian/Ubuntu: apt install gcc-mingw-w64-x86-64)."
need makensis "Install NSIS (Debian/Ubuntu: apt install nsis)."
need python3 "Install Python 3.11+."

VERSION="$(sed -n 's/^version *= *"\(.*\)"/\1/p' "$ROOT/Cargo.toml" | head -n1)"
echo "==> Lillith $VERSION for Windows ($TARGET)"

if [[ "${SKIP_BUILD:-}" != 1 ]]; then
  cd "$ROOT"
  # The Win32 overlay is cfg(windows); Wayland/X11 backends are off.
  "$CARGO" build --release --locked --target "$TARGET" \
    -p lillith --no-default-features --features windows
  "$CARGO" build --release --locked --target "$TARGET" -p lillith-settings-gui
  # Elevated helper (requireAdministrator manifest embedded by its build.rs).
  "$CARGO" build --release --locked --target "$TARGET" -p lillith-admin
fi
BIN="$TARGET_DIR/$TARGET/release"

echo "==> staging $STAGE"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp "$BIN/lillith.exe" "$BIN/lillith-settings.exe" "$BIN/lillith-admin.exe" "$STAGE/"
python3 "$HERE/stage-assets.py" "$STAGE"
[[ -f "$HERE/lillith.ico" ]] || python3 "$ROOT/branding/make-icons.py"
cp "$HERE/lillith.ico" "$STAGE/"
# The icon set: icons\<id>.ico (shortcut icons) + 64/128 px PNGs (Settings >
# Icon thumbnails, window icon). icons.nsh feeds the installer's icon page.
ICONS_NSH="$(dirname "$STAGE")/icons.nsh"
python3 - "$ROOT/branding" "$STAGE/icons" "$ICONS_NSH" <<'PY'
import shutil, sys, tomllib
from pathlib import Path
branding, out, nsh = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
reg = tomllib.loads((branding / "icons.toml").read_text())
out.mkdir(parents=True)
lines = ["; generated by windows/build.sh from branding/icons.toml",
         f'!define ICON_DEFAULT "{reg["default"]}"',
         "!macro FillIconList hwnd"]
for i in reg["icon"]:
    shutil.copy(branding / i["ico"], out / f'{i["id"]}.ico')
    for s in (64, 128):
        d = out / i["id"]
        d.mkdir(exist_ok=True)
        shutil.copy(branding / i["png"].replace("{size}", str(s)), d / f"lillith-{s}.png")
    lines.append(f'  ${{NSD_CB_AddString}} ${{hwnd}} "{i["name"]}"')
lines += ["!macroend", "; $IconName -> $IconId (\"\" = keep the configured icon)", "Function IconIdOfName",
          '  StrCpy $IconId ""']
for i in reg["icon"]:
    lines.append(f'  ${{If}} $IconName == "{i["name"]}"\n    StrCpy $IconId "{i["id"]}"\n  ${{EndIf}}')
lines += ["FunctionEnd", "; /ICON=<id> check: $IconId -> $IconName (\"\" if unknown)", "Function IconNameOfId",
          '  StrCpy $IconName ""']
for i in reg["icon"]:
    lines.append(f'  ${{If}} $IconId == "{i["id"]}"\n    StrCpy $IconName "{i["name"]}"\n  ${{EndIf}}')
lines.append("FunctionEnd")
nsh.write_text("\n".join(lines) + "\n")
print(f"  {len(reg['icon'])} icons -> {out}")
PY
cp "$HERE/INSTALL-windows.md" "$STAGE/INSTALL-windows.txt"
cp "$ROOT/LICENSE" "$STAGE/LICENSE.txt"
cp "$ROOT/LICENSE-ASSETS.md" "$STAGE/LICENSE-ASSETS.txt"
cp "$ROOT/assets/config.example.toml" "$STAGE/config.example.toml"
# Pose Builder: the import pipeline (tools\video-pipeline\*.py, found next to
# the exe) and its AI cut-out model in <install dir>\models\rembg.
mkdir -p "$STAGE/tools/video-pipeline"
cp "$ROOT"/tools/video-pipeline/*.py "$STAGE/tools/video-pipeline/"
if [[ "${NO_MATTE_MODEL:-}" == 1 ]]; then
  echo "==> NO_MATTE_MODEL=1: no AI cut-out model (Pose Builder uses the backdrop key)"
else
  bash "$ROOT/tools/release/stage-matte-model.sh" "$STAGE/models"
fi
LLAMA_SRC="$ROOT/bundle/llama/windows-x64"
if [[ "${NO_LLAMA:-}" != 1 && -f "$LLAMA_SRC/llama-server.exe" ]]; then
  echo "==> bundling llama-server ($(head -n1 "$LLAMA_SRC/BUNDLE.txt" 2>/dev/null || echo windows-x64))"
  mkdir -p "$STAGE/bundle/llama" "$STAGE/bundle/models"
  cp -r "$LLAMA_SRC" "$STAGE/bundle/llama/windows-x64"
  cp "$ROOT/bundle/llama/llama.lock" "$STAGE/bundle/llama/"
  cp "$ROOT/bundle/models/README.txt" "$STAGE/bundle/models/README.txt"
else
  echo "==> no bundled llama-server (run tools/bundle/make-bundle.sh --fetch-only to include it)"
fi

VOICE_ARGS=()
VOICE_STAGE=""
if [[ -n "${VOICE_PAYLOAD:-}" ]]; then
  [[ -f "$VOICE_PAYLOAD" ]] || { echo "error: VOICE_PAYLOAD=$VOICE_PAYLOAD not found" >&2; exit 1; }
  if [[ -f "$VOICE_PAYLOAD.sha256" ]]; then
    (cd "$(dirname "$VOICE_PAYLOAD")" && sha256sum -c --quiet "$(basename "$VOICE_PAYLOAD").sha256")
  fi
  VOICE_STAGE="$(dirname "$STAGE")/voice-payload"
  echo "==> voice payload $(basename "$VOICE_PAYLOAD") -> $VOICE_STAGE"
  rm -rf "$VOICE_STAGE"; mkdir -p "$VOICE_STAGE"
  python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$VOICE_PAYLOAD" "$VOICE_STAGE"
  [[ -f "$VOICE_STAGE/voice/python/pythonw.exe" && -f "$VOICE_STAGE/voice/models/pocket/voices/lillith.npy" ]] \
    || { echo "error: $VOICE_PAYLOAD is not a voice-win payload (voice/python, voice/models)" >&2; exit 1; }
  (cd "$VOICE_STAGE/voice" && sha256sum -c --quiet SHA256SUMS) || { echo "error: voice payload SHA256SUMS mismatch" >&2; exit 1; }
  VOICE_ARGS=(-DVOICE="$VOICE_STAGE/voice")
fi

mkdir -p "$DIST"
SETUP="$DIST/Lillith-$VERSION-setup.exe"
echo "==> makensis -> $SETUP"
makensis -V2 -INPUTCHARSET UTF8 \
  -DVERSION="$VERSION" -DSTAGE="$STAGE" -DOUTFILE="$SETUP" -DICON="$HERE/lillith.ico" \
  -DICONS_NSH="$ICONS_NSH" "${VOICE_ARGS[@]}" \
  "$HERE/installer.nsi"

if [[ "${NO_ZIP:-}" != 1 ]]; then
  ZIP="$DIST/Lillith-$VERSION-windows-x64.zip"
  echo "==> zip -> $ZIP"
  rm -f "$ZIP"
  # Lillith\ (+ Lillith\voice\ when VOICE_PAYLOAD is set: the daemon finds its
  # models next to its own python\, so the portable copy works from any folder)
  python3 - "$(dirname "$STAGE")" "$ZIP" "$VOICE_STAGE" <<'PY'
import os, sys, zipfile
root, zp, voice = sys.argv[1], sys.argv[2], sys.argv[3]
def walk(base, arc):
    for d, _, fs in os.walk(base):
        for f in sorted(fs):
            p = os.path.join(d, f)
            yield p, arc + "/" + os.path.relpath(p, base).replace(os.sep, "/")
with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED, allowZip64=True) as z:
    for p, a in walk(os.path.join(root, "Lillith"), "Lillith"):
        z.write(p, a)
    if voice:
        for p, a in walk(os.path.join(voice, "voice"), "Lillith/voice"):
            z.write(p, a)
        z.writestr("Lillith/Start Lillith with voice.cmd",
                   "@echo off\r\nrem Portable copy: starts Lillith's voice (hidden, \\\\.\\pipe\\lillith-voice) and Lillith.\r\n"
                   "rem The installer instead autostarts the voice at sign-in (HKCU Run).\r\n"
                   "rem It starts the voice if needed, waits until it answers, then starts lillith.exe.\r\n"
                   'start "" "%~dp0voice\\python\\pythonw.exe" -m lillith_voice.winlaunch --start-app "%~dp0lillith.exe"\r\n')
PY
fi

(cd "$DIST" && sha256sum Lillith-"$VERSION"-* > SHA256SUMS)
ls -l "$DIST"
echo "==> done"
